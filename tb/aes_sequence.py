@cocotb.test(timeout_time=SOAK_TIMEOUT_MS, timeout_unit="ms")
async def all_mode_keysize_matrix(dut):
    """Every (mode, direction, key size) combination on a two-block message.

    The completeness sweep: 5 modes x 2 directions x 3 key sizes. Each cell is
    scored against the model with whatever context the DUT reported or was
    given, so one cell failing does not mask the rest.
    """
    banner(dut, "TC50: full mode x direction x key-size matrix")
    env = await bringup(dut)
    rng = random.Random(0x3A7819)
    failures = []
    for mode in ("ECB", "CBC", "CFB", "OFB", "CTR"):
        for decrypt in (False, True):
            for bits, key in KEYS.items():
                cfg = AesConfig(mode, key, decrypt=decrypt)
                blocks = rand_blocks(rng, 2)
                ctx = 0 if cfg.needs_generated_iv else IV_38A
                await reset_dut(dut)
                try:
                    await run_and_check(dut, cfg, blocks, context=ctx,
                                        label=f"TC50 {cfg}")
                    dut._log.info(f"  {cfg}: PASS")
                except AssertionError as e:
                    failures.append(f"{cfg}: {str(e).splitlines()[0]}")
                    dut._log.error(f"  {cfg}: FAIL")
    assert not failures, (
        f"{len(failures)} of 30 mode/direction/key-size cells failed:\n  "
        + "\n  ".join(failures))
    env.checker.check()


