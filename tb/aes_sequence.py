@cocotb.test(timeout_time=TIMEOUT_MS, timeout_unit="ms")
async def cfb_outvalid_waits_for_final_segment(dut):
    """CFB must not assert outVALID until the last segment has been computed.

    aes.sv:577 raises outVALID whenever `seg_cntr == seg_cntr_lim`, with no
    `cipher_done` term. Two consequences:

      * CFB128 (cfb_seg_bits = 3'b101) is not listed in the seg_cntr_lim case at
        aes.sv:284-291, so it takes `default: 4'h0`. seg_cntr is also 0 on entry
        to SHOOT, so the condition is true on the very first cycle and outVALID
        rises before a single cipher run has finished. The `else if` at
        aes.sv:578 that was written to handle CFB128 can never be reached.
      * For s < 128 the same condition is true on entry to the *final* segment,
        so outVALID rises one whole cipher run before that segment's result is
        merged into output_block.

    Counting completed cipher runs before outVALID rises measures this directly:
    it must be 128/s, not 128/s - 1 and not 0.
    """
    banner(dut, "TC24b: outVALID must wait for the final CFB segment")
    env = await bringup(dut)
    done = probe(dut, "AES.cipher_done")
    if done is None:
        dut._log.warning("  AES.cipher_done not visible -- skipping")
        return

    failures = []
    for s in (128, 64, 32, 16):
        await reset_dut(dut)
        cfg = AesConfig("CFB", KEY_128, cfb_seg_bits=s)
        apply_config(dut, cfg)
        await send_block(dut, PT_38A[0], first=True)

        runs, prev = 0, int(done.value)
        for _ in range(BLOCK_TIMEOUT):
            await FallingEdge(dut.clk)
            cur = int(done.value)
            if cur and not prev:
                runs += 1
            prev = cur
            if int(dut.outVALID.value):
                break
        want_runs = 128 // s
        dut._log.info(f"  CFB{s}: {runs} cipher run(s) completed before outVALID, "
                      f"expected {want_runs}")
        if runs != want_runs:
            failures.append(f"CFB{s}: outVALID after {runs} cipher runs, "
                            f"expected {want_runs}")
        dut.outREADY.value = 1
        await RisingEdge(dut.clk)
        dut.outREADY.value = 0

    assert not failures, (
        "outVALID is asserted before the block is complete:\n  "
        + "\n  ".join(failures)
        + "\n  aes.sv:577 tests `seg_cntr == seg_cntr_lim` with no cipher_done "
          "term. Add it (and give CFB128 its own seg_cntr_lim entry, or handle "
          "3'b101 before the equality test), or every CFB block is handed to the "
          "consumer with its last segment missing")


