def rtl_blocks(hex_list):
    return [nist_bytes_to_rtl_state(list(bytes.fromhex(h))) for h in hex_list]


def banner(dut, text):
    dut._log.info("=" * 70)
    dut._log.info(text)
    dut._log.info("=" * 70)


async def run_and_check(dut, cfg, blocks, *, context=None, partial_bits=None,
                        ready_delay=0, send_gap=0, label="", ctr_increment="nist"):
    """Push a message through the DUT and scoreboard it.

    For the paths that generate their own IV/counter (CBC/CFB/OFB encryption,
    CTR encryption) the chaining context is whatever the DUT reports on
    `encCntxtOut`; the reference is then computed from that value, so the test
    checks the mode algorithm rather than re-deriving an IV it cannot know.
    Whether that reported context is itself sane -- fresh, unique, actually the
    one used -- is a separate question, asked by the IV tests.
    """
    apply_config(dut, cfg)
    res = await run_message(dut, cfg, blocks, enc_cntxt_in=(context or 0),
                            partial_bits=partial_bits, ready_delay=ready_delay,
                            send_gap=send_gap)
    used = res.enc_cntxt_out if cfg.needs_generated_iv or (
        cfg.mode == "CTR" and not cfg.decrypt) else (context or 0)
    want = expected_outputs(cfg, blocks, used, partial_bits=partial_bits,
                            ctr_increment=ctr_increment)
    compare(dut, cfg, res.outputs, want, context=used, label=label or str(cfg))
    return res, used


