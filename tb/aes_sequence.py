async def check_partial_masking(dut, mode, valid_bits_list, label):
    """Shared body for the OFB and CTR partial-final-block tests.

    `partial` and `valid_bits` are read in the SHOOT state (aes.sv:636-637 for
    OFB, 685-686 for CTR), i.e. after `inREADY` has been seen and a Case-1
    sender has already released them. Each width is therefore run twice: once
    with the discipline aes.sv:81-88 actually promises, and once holding the
    sideband all the way to `outVALID`. If the second passes where the first
    failed, the masking depends on a hold the interface does not require, and
    the failure message says so instead of leaving it as a bare mismatch.
    """
    results = []
    for valid_bits in valid_bits_list:
        await reset_dut(dut)
        cfg1 = AesConfig(mode, KEY_128, hold=HoldStyle.CASE1)
        apply_config(dut, cfg1)
        r1 = await run_message(dut, cfg1, PT_38A[:2], partial_bits=valid_bits)
        ctx1 = r1.enc_cntxt_out
        want1 = expected_outputs(cfg1, PT_38A[:2], ctx1, partial_bits=valid_bits)
        ok_case1 = r1.outputs == want1

        await reset_dut(dut)
        cfg2 = AesConfig(mode, KEY_128, hold=HoldStyle.THROUGH_OUTPUT)
        apply_config(dut, cfg2)
        r2 = await run_message(dut, cfg2, PT_38A[:2], partial_bits=valid_bits)
        ctx2 = r2.enc_cntxt_out
        want2 = expected_outputs(cfg2, PT_38A[:2], ctx2, partial_bits=valid_bits)
        ok_case2 = r2.outputs == want2

        results.append((valid_bits, ok_case1, ok_case2))
        dut._log.info(f"  valid_bits={valid_bits:3d}: "
                      f"Case-1 hold {'OK ' if ok_case1 else 'BAD'}   "
                      f"held-to-outVALID {'OK ' if ok_case2 else 'BAD'}")
        if not ok_case1:
            dut._log.warning(f"    Case-1 final block got  "
                             f"{rtl_hex(r1.outputs[-1])}")
            dut._log.warning(f"    Case-1 final block want {rtl_hex(want1[-1])}")

    broken = [v for v, c1, _ in results if not c1]
    needs_hold = [v for v, c1, c2 in results if not c1 and c2]
    assert not broken, (
        f"{label}: partial masking failed for valid_bits={broken} under the "
        f"Case-1 hold discipline.\n"
        f"  Widths that then worked when the sideband was held to outVALID: "
        f"{needs_hold or 'none'}.\n"
        f"  aes.sv reads `partial`/`valid_bits` combinationally in SHOOT, but "
        f"aes.sv:81-88 lets the sender release every input-channel signal as "
        f"soon as inREADY is seen. Both must be latched at the input handshake "
        f"and the latched copies used in SHOOT -- the same fix `first` needs on "
        f"the CBC decrypt path (TC21)")


