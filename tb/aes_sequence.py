@cocotb.test(timeout_time=TIMEOUT_MS, timeout_unit="ms")
async def input_capture_requires_inready(dut):
    """The DUT must not latch input_block on a cycle where inREADY is low.

    aes.sv captures with `cipherIn <= (inVALID) ? input_block : cipherIn` and
    asserts `inREADY <= 1` on the same edge, so the transfer is taken on a cycle
    where a VALID/READY master still sees READY low. This watches the internal
    capture register and the handshake together and reports the ordering.
    """
    banner(dut, "TC42: input capture vs inREADY ordering")
    env = await bringup(dut)
    cfg = AesConfig("ECB", KEY_128)
    apply_config(dut, cfg)
    cin = probe(dut, "AES.cipherIn")
    if cin is None:
        dut._log.warning("  AES.cipherIn not visible -- skipping the internal check")
        return

    dut.input_block.value = PT_38A[0]
    dut.first.value = 1
    dut.inVALID.value = 1
    captured_at = None
    ready_at = None
    for cyc in range(200):
        await RisingEdge(dut.clk)
        if captured_at is None and int(cin.value) == PT_38A[0]:
            captured_at = cyc
        if ready_at is None and int(dut.inREADY.value):
            ready_at = cyc
        if captured_at is not None and ready_at is not None:
            break
    dut.inVALID.value = 0
    dut._log.info(f"  input latched on cycle {captured_at}, "
                  f"inREADY first high on cycle {ready_at}")
    assert captured_at is not None, "input_block was never captured"
    assert ready_at is not None and ready_at <= captured_at, (
        f"input_block was latched on cycle {captured_at} but inREADY did not go "
        f"high until cycle {ready_at}. The DUT consumed a block on a cycle where "
        f"a VALID/READY master had not yet been granted the transfer, so a "
        f"master that changes its data on the next edge (which it is entitled to "
        f"do once it does see READY) can have the wrong block encrypted")
    await recv_block(dut)
    env.checker.check()


