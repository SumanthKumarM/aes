@cocotb.test(timeout_time=TIMEOUT_MS, timeout_unit="ms")
async def invalid_mode_is_inert(dut):
    """mode[2:0] of 000/110/111 produces no handshake and no output.

    aes.sv:705-720's `default` branch parks everything. An undecoded mode must
    never look like a working one -- silently encrypting under an unintended
    mode is worse than refusing.
    """
    banner(dut, "TC7: undecoded mode values are inert")
    env = await bringup(dut)
    for bad in INVALID_MODES:
        await reset_dut(dut)
        dut.mode.value = bad
        dut.key_size.value = 0b01
        dut.master_key.value = AesModeModel(KEY_128).master_key_rtl
        dut.input_block.value = PT_38A[0]
        dut.first.value = 1
        dut.inVALID.value = 1
        dut.outREADY.value = 1
        await ClockCycles(dut.clk, 500)
        assert int(dut.inREADY.value) == 0, (
            f"mode=0b{bad:03b} asserted inREADY -- an undecoded mode accepted a "
            f"block it has no algorithm for")
        assert int(dut.outVALID.value) == 0, (
            f"mode=0b{bad:03b} asserted outVALID")
        assert int(dut.output_block.value) == 0, (
            f"mode=0b{bad:03b} produced output 0x{int(dut.output_block.value):032x}")
        dut._log.info(f"  mode=0b{bad:03b}: inert as expected")
    env.checker.check()


@cocotb.test(timeout_time=TIMEOUT_MS, timeout_unit="ms")
async def invalid_cfb_segment(dut):
    """An out-of-spec cfb_seg_bits must stay contained: no hang, no damage.

    SCOPE. `cfb_seg_bits` of 000/110/111 is out of spec (aes.sv:91-100 defines
    only 001..101). What the block *should* do about that is an open design
    decision, not something the RTL has ever promised:

        (a) don't care -- out-of-spec config is a software bug   <- today
        (b) refuse     -- stay parked, never handshake           <- what an
                          undecoded mode[2:0] already does
        (c) report     -- raise segINVALID                       <- planned in
                          docs/status_register.md

    An earlier version of this test asserted (b). That was the testbench
    encoding an opinion as a requirement, and it is not asserted here. What IS
    asserted is the property that holds under every one of the three policies
    and that a consumer genuinely depends on: a misconfigured request must not
    hang the block, and must not damage the traffic that follows it.

    The observed handshake behaviour is logged rather than checked, so the
    current policy is visible in the run without failing it.

    TODO: once the status register lands, tighten this to assert the chosen
    policy -- for (c), that segINVALID is raised for exactly these encodings.
    """
    banner(dut, "TC8: out-of-spec cfb_seg_bits stays contained")
    env = await bringup(dut)
    good = AesConfig("CFB", KEY_128, cfb_seg_bits=128)

    for bad in INVALID_CFB_SEGS:
        await reset_dut(dut)
        dut.mode.value = 0b0011               # CFB encrypt
        dut.key_size.value = 0b01
        dut.master_key.value = AesModeModel(KEY_128).master_key_rtl
        dut.cfb_seg_bits.value = bad
        dut.input_block.value = PT_38A[0]
        dut.first.value = 1
        dut.inVALID.value = 1
        dut.outREADY.value = 1

        # Long enough for the IV pipeline (~1100 clk) plus a full block, so a
        # "no output" result means the configuration really is inert rather than
        # merely slow.
        got_valid, got_data, got_ctx = 0, 0, 0
        for _ in range(CONFIG_SETTLE):
            await FallingEdge(dut.clk)
            if int(dut.outVALID.value):
                got_valid = 1
                got_data = int(dut.output_block.value)
                got_ctx = int(dut.encCntxtOut.value)
                break
        policy = ("(b) refused -- stayed parked" if not got_valid else
                  "(a) handshook out zeros" if got_data == 0 else
                  "handshook out NON-zero data")
        dut._log.info(f"  cfb_seg_bits=0b{bad:03b}: outVALID={got_valid} "
                      f"output=0x{got_data:032x}  -> policy {policy}")
        if got_valid and got_ctx:
            dut._log.info(f"    note: consumed a generated IV "
                          f"(encCntxtOut=0x{got_ctx:032x}) for a request it "
                          f"cannot service")

        # Release the bus, then -- deliberately WITHOUT a reset -- run a real
        # CFB128 message. This is the containment check: whatever the block did
        # with the bogus request, it must not have left chaining state, a stuck
        # seg_cntr or a half-open handshake behind.
        await RisingEdge(dut.clk)
        dut.inVALID.value = 0
        dut.outREADY.value = 0
        dut.first.value = 0
        dut.input_block.value = 0

        assert int(dut.outVALID.value) == 0 or got_valid, (
            f"cfb_seg_bits=0b{bad:03b}: outVALID is asserted but was never seen "
            f"to rise -- the handshake is stuck. {dut_state(dut)}")

        apply_config(dut, good)
        res = await run_message(dut, good, PT_38A[:2])
        want = good.model().cfb_encrypt(PT_38A[:2], res.enc_cntxt_out, 128)
        compare(dut, good, res.outputs, want, context=res.enc_cntxt_out,
                label=f"TC8 valid CFB128 message after cfb_seg_bits=0b{bad:03b}")
        dut._log.info(f"    a following valid CFB128 message is unaffected")
    env.checker.check()


def zero_round_result(pt, key):
    """plaintext XOR w[0..3] -- what an Nr=0 'encryption' would emit."""
    m = AesModeModel(key)
    s = _add_round_key(rtl_state_to_nist_bytes(pt), m._enc.round_key(0))
    return nist_bytes_to_rtl_state(s)


@cocotb.test(timeout_time=TIMEOUT_MS, timeout_unit="ms")
async def key_size_reset_value(dut):
    """key_size=00 is documented as a reset value, not a key length.

    aes.sv:50-53 lists 00 as "reset value". cipher.sv:48 derives Nr from it as
    `{key_size[1]|key_size[0], key_size[1], key_size[0], 0}` = 0, so a cipher
    started with key_size=00 has Nr=0. Whatever the design intends, it must not
    hand out a block produced by a zero-round AES.
    """
    banner(dut, "TC9: key_size=00 must not produce a zero-round ciphertext")
    env = await bringup(dut)
    dut.mode.value = 0b0001
    dut.key_size.value = 0b00
    dut.master_key.value = AesModeModel(KEY_128).master_key_rtl
    dut.input_block.value = PT_38A[0]
    dut.first.value = 1
    dut.inVALID.value = 1
    dut.outREADY.value = 1
    await ClockCycles(dut.clk, 3000)
    if int(dut.outVALID.value):
        got = int(dut.output_block.value)
        assert got != zero_round_result(PT_38A[0], KEY_128), (
            f"key_size=00 produced {rtl_hex(got)}, which is exactly "
            f"plaintext XOR round-key-0 -- a single AddRoundKey with no rounds. "
            f"That is not encryption; the reset key_size value must be rejected "
            f"rather than run")
    else:
        dut._log.info("  key_size=00: inert (no outVALID) -- acceptable")
    env.checker.check()


@cocotb.test(timeout_time=TIMEOUT_MS, timeout_unit="ms")
async def mode_switch_between_messages(dut):
    """Switching mode between messages does not leak chaining state.

    Each mode's branch zeroes the registers it does not use, so a CBC message
    followed by an ECB message must give exactly the ECB answer -- no residual
    XOR with a leftover ciphertext or IV.
    """
    banner(dut, "TC10: ECB after CBC after ECB, no state leakage")
    env = await bringup(dut)
