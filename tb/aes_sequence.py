@cocotb.test(timeout_time=TIMEOUT_MS, timeout_unit="ms")
async def cfb_input_capture_is_gated(dut):
    """A streaming sender must not corrupt the CFB block already in flight.

    aes.sv:505 captures `temp <= input_block` on `inVALID` alone, not on
    `inVALID && inREADY`. CFB re-enters ARM between every segment with
    `inREADY` deasserted (aes.sv:502), so a sender that keeps `inVALID` high --
    perfectly legal, it is waiting for READY -- overwrites the block being
    segmented. This presents the next block early and checks the first one still
    comes out right.
    """
    banner(dut, "TC29: input capture must be gated on inREADY, not inVALID alone")
    env = await bringup(dut)
    key = KEY_128
    cfg = AesConfig("CFB", key, cfb_seg_bits=16)
    apply_config(dut, cfg)

    # Accept block 0 normally.
    await send_block(dut, PT_38A[0], first=True)
    # Immediately present block 1 and hold it, as a streaming sender would while
    # waiting for inREADY. inREADY is low for the whole of block 0's segments.
    dut.input_block.value = PT_38A[1]
    dut.inVALID.value = 1
    out0 = await recv_block(dut)
    dut.inVALID.value = 0

    iv = out0.enc_cntxt_out
    want = cfg.model().cfb_encrypt([PT_38A[0]], iv, 16)[0]
    assert out0.data == want, (
        f"CFB16 block 0 = {rtl_hex(out0.data)}, want {rtl_hex(want)}.\n"
        f"  The next block was presented on input_block while inREADY was low. "
        f"aes.sv:505 latches `temp` on inVALID alone, so the block being "
        f"segmented was replaced mid-flight. The capture must be qualified with "
        f"inREADY -- a sender holding VALID until READY is the normal case, not "
        f"a protocol violation")
    env.checker.check()


