"""
Cocotb testbench for the AES top block (`aes.sv`), driven through `aes_top.sv`.

    make run_test_suite block=aes_top
    make run_test       block=aes_top test=ecb_sp80038a_encrypt

STRUCTURE
---------
This file holds test bodies only. The layers underneath it are separate modules
so they can be reasoned about (and reused) on their own:

    aes_ref_model.py   golden reference for all five modes, self-checked
                       against NIST SP 800-38A Appendix F at import time
    aes_testbench.py   bus driver, output monitor, continuous protocol checker,
                       dual-domain noise sources, bring-up
    aes_top.sv         flat-port wrapper generated by rtl/gen_top.py -- aes.sv's
                       only port is a SystemVerilog interface, which Verilator
                       cannot elaborate as a simulation top

The block-level TBs in this directory are single ~1000-line files that each
re-implement the AES S-box, the key schedule and a `NoiseBitBuffer`. Nothing is
duplicated here: the block cipher is imported from cipher_tb/invCipher_tb via
aes_ref_model, and there is exactly one `wait_signal` signature.

WHAT IS BEING TESTED
--------------------
`aes.sv` is a mode wrapper. The AES round datapath itself is already covered by
cipher_tb / invCipher_tb / sbox_tb, so the value at this level is in everything
those cannot see:

  * the five mode algorithms end to end against published vectors,
  * the chaining state that carries from block to block within a message, and
    that must NOT carry from one message to the next,
  * the VALID/READY contract in both directions, including backpressure and
    idle senders,
  * the IV/counter context ports -- what the DUT reports, what it accepts, and
    whether a counter can ever repeat,
  * reset, enable-gating and invalid configuration,
  * whether a signal the interface says may be dropped after `inREADY` is in
    fact still needed later.

TEST NAMING
-----------
Descriptive names with a `# ==== TCn ====` banner, matching the newest block TBs
(trng_tb, cbc_mac_tb, iv_gen_tb) and keeping `test=<name>` readable.

A NOTE ON EXPECTED FAILURES
---------------------------
Nothing here is written to pass. Each test asserts what the design documents or
what the relevant standard requires, and the assertion message says which. A
failure is a statement about the RTL, not a knob to turn.
"""

