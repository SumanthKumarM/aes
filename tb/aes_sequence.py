@cocotb.test(timeout_time=SOAK_TIMEOUT_MS, timeout_unit="ms")
async def long_random_soak(dut):
    """A long randomized stream: random mode, key, length and handshake timing.

    Everything the directed tests fix, this varies. The point is coverage of
    combinations nobody thought to enumerate, with a fixed seed so any failure
    is reproducible from the log.
    """
    banner(dut, "TC52: randomized soak")
    env = await bringup(dut)
    rng = random.Random(0x50A17)
    for msg in range(14):
        mode = rng.choice(["ECB", "CBC", "CFB", "OFB", "CTR"])
        decrypt = rng.random() < 0.5
        bits = rng.choice([128, 192, 256])
        seg = rng.choice([128, 64, 32]) if mode == "CFB" else 128
        cfg = AesConfig(mode, KEYS[bits], decrypt=decrypt, cfb_seg_bits=seg)
        blocks = rand_blocks(rng, rng.randint(1, 4))
        ctx = 0 if cfg.needs_generated_iv else rng.getrandbits(128)
        await reset_dut(dut)
        await run_and_check(dut, cfg, blocks, context=ctx,
                            ready_delay=rng.choice([0, 0, 2, 13]),
                            send_gap=rng.choice([0, 0, 1, 7]),
                            label=f"TC52 msg{msg} {cfg}")
        dut._log.info(f"  msg{msg}: {cfg} x{len(blocks)} OK")
    env.checker.check()
