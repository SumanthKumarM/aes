@cocotb.test(timeout_time=TIMEOUT_MS, timeout_unit="ms")
async def iv_generation_latency(dut):
    """The first IV arrives within the documented pipeline budget, and is consumed.

    iv_gen must condition a 384-bit seed (~1200 clk) and run CTR_DRBG
    Instantiate plus one Generate (~260 clk) before the first CBC block can
    start. This measures it and confirms the AES actually handshakes the IV
    (`aes_iv_ready`) rather than free-running on a stale value.
    """
    banner(dut, "TC47: first-IV latency and handshake")
    env = await bringup(dut)
    cfg = AesConfig("CBC", KEY_128)
    apply_config(dut, cfg)

    iv_ready = probe(dut, "AES.aes_iv_ready")
    saw_ready = False
    if iv_ready is not None:
        async def watch():
            nonlocal saw_ready
            while True:
                await FallingEdge(dut.clk)
                if int(iv_ready.value):
                    saw_ready = True
        cocotb.start_soon(watch())

    cycles = await send_block(dut, PT_38A[0], first=True)
    res = await recv_block(dut)
    dut._log.info(f"  first CBC block accepted after {cycles} cycles, "
                  f"IV = {rtl_hex(res.enc_cntxt_out)}")
    assert cycles < IV_TIMEOUT, f"first IV took {cycles} cycles"
    if iv_ready is not None:
        assert saw_ready, (
            "aes_iv_ready never asserted -- the AES took an IV without "
            "completing iv_gen's VALID/READY handshake, so CTR_DRBG was never "
            "told to advance and the next message would reuse this IV")
    env.checker.check()


@cocotb.test(timeout_time=TIMEOUT_MS, timeout_unit="ms")
async def iv_not_requested_in_ecb_and_ctr(dut):
    """ECB and CTR never assert aes_iv_ready.

    Neither mode needs a generated IV (aes.sv:379, 700). Consuming one anyway
    would burn DRBG output and, worse, make ECB's timing depend on the entropy
    pipeline.
    """
    banner(dut, "TC48: no IV consumed in ECB or CTR")
    env = await bringup(dut)
    iv_ready = probe(dut, "AES.aes_iv_ready")
    if iv_ready is None:
        dut._log.warning("  AES.aes_iv_ready not visible -- skipping")
        return
    for mode in ("ECB", "CTR"):
        await reset_dut(dut)
        cfg = AesConfig(mode, KEY_128)
        apply_config(dut, cfg)
        violations = []

        async def watch():
            while True:
                await FallingEdge(dut.clk)
                if int(iv_ready.value):
                    violations.append(1)
        t = cocotb.start_soon(watch())
        await run_message(dut, cfg, PT_38A[:2])
        t.cancel()
        assert not violations, (
            f"{mode} asserted aes_iv_ready {len(violations)} times -- it "
            f"consumed IVs from CTR_DRBG that it has no use for")
        dut._log.info(f"  {mode}: aes_iv_ready never asserted")
    env.checker.check()


@cocotb.test(timeout_time=TIMEOUT_MS, timeout_unit="ms")
async def entropy_failure_does_not_hang_silently(dut):
    """A stuck noise source must not leave the AES waiting forever with no signal.

    Forcing raw_rand_bit_cbc_mac to a constant trips the Repetition Count Test
    inside cbc_mac, which drives iv_gen's CTR_DRBG to UNINSTANTIATE. A CBC
    encryption blocked on `iv_valid` then stalls. There is no status output on
    `aes_interface` for this, so the stall is indistinguishable from a slow IV --
    which is the finding this test records.
    """
    banner(dut, "TC49: entropy failure while a CBC message is waiting for an IV")
    env = await bringup(dut)
    env.set_cbcmac_noise("stuck_1")
    cfg = AesConfig("CBC", KEY_128)
    apply_config(dut, cfg)

    dut.input_block.value = PT_38A[0]
    dut.first.value = 1
    dut.inVALID.value = 1
    accepted = False
    for _ in range(20000):
        await FallingEdge(dut.clk)
        if int(dut.inREADY.value):
            accepted = True
            break
    dut.inVALID.value = 0
    dut._log.info(f"  with a stuck noise source, block accepted = {accepted}")

    # Recover: healthy entropy plus a reset must bring the DUT back.
    env.set_cbcmac_noise("physics", offset=21000)
    await reset_dut(dut)
    apply_config(dut, cfg)
    await run_and_check(dut, cfg, PT_38A[:1], label="TC49 post-recovery CBC")
    dut._log.info("  recovered after reset with healthy entropy")
    assert not accepted, (
        "the AES accepted a CBC block while the entropy source was stuck and "
        "the health tests had failed. Either it used an IV derived from failed "
        "entropy, or iv_valid is not actually gating acceptance")
    env.checker.check()


